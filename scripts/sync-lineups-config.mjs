import { readFileSync, writeFileSync } from "node:fs";
import { resolve } from "node:path";

const sourcePath = resolve(process.cwd(), "config/lineups.json");
const targetPath = resolve(process.cwd(), "lib/server/lineups-config.generated.mjs");
function stripGeneratedLineupMetadata(value) {
  if (Array.isArray(value)) return value.map(stripGeneratedLineupMetadata);
  if (value && typeof value === "object") {
    return Object.fromEntries(
      Object.entries(value)
        .filter(([key]) => key !== "updated")
        .map(([key, item]) => [key, stripGeneratedLineupMetadata(item)]),
    );
  }
  return value;
}

const parsed = stripGeneratedLineupMetadata(JSON.parse(readFileSync(sourcePath, "utf8")));
const output = [
  "// GENERATED FROM config/lineups.json. Do not edit this file directly.",
  `export default ${JSON.stringify(parsed, null, 2)};`,
  "",
].join("\n");
writeFileSync(targetPath, output, "utf8");
console.log(`Synced ${targetPath} from ${sourcePath}`);
